/**
 * Builds a positional row aligned to `headers`, starting from the valid
 * row and applying `overrides` (keyed by trimmed header).
 */
export function makeRow(
  overrides: Record<string, string> = {},
  headers: string[] = REAL_MASTER_SHEET_HEADERS,
  base: Record<string, string> = VALID_ROW_VALUES,
): string[] {
  const values = { ...base, ...overrides };
  return headers.map((h) => values[h.trim()] ?? "");
}
